/** Generates supabase/seed.sql from the TypeScript catalogue so the two can never drift. Run: npm run seed:gen */
import { writeFileSync } from "node:fs";
import { CATALOGUE } from "../src/content/catalogue";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
let sql = "-- GENERATED by scripts/gen-seed.ts from src/content/catalogue.ts. Do not edit by hand.\n";
sql += "-- Catalogue entries are plans. Only 'demo' and 'published' procedures have playable content.\n\n";
CATALOGUE.forEach((s, i) => {
  sql += `insert into specialties(slug, name, cross_specialty, sort) values (${q(s.slug)}, ${q(s.name)}, ${!!s.crossSpecialty}, ${i}) on conflict (slug) do update set name = excluded.name, sort = excluded.sort;\n`;
  sql += `insert into procedures(specialty_id, slug, name, catalogue_status, sort)\nselect id, v.slug, v.name, v.status, v.sort from specialties, (values\n`;
  sql += s.procedures.map((p, j) => `  (${q(p.slug)}, ${q(p.name)}, ${q(p.status)}, ${j})`).join(",\n");
  sql += `\n) as v(slug, name, status, sort) where specialties.slug = ${q(s.slug)}\non conflict (slug) do update set name = excluded.name, sort = excluded.sort;\n\n`;
});
writeFileSync("supabase/seed.sql", sql);
console.log(`Wrote supabase/seed.sql: ${CATALOGUE.length} specialties, ${CATALOGUE.reduce((a, s) => a + s.procedures.length, 0)} procedures`);
